// plate-factory stage 8 (DEC-39): audio-options offers the active pack's tracks and SFX by name, else
// the audio files in one folder the user names, else nothing (narration only). It never searches.
// The fixture pack is brand-min plus a generated tone: no real audio lives in the repo.
import { test, before } from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { run, fx, ROOT, tmpDir } from '../helpers/run.mjs';
import { pcmToWav } from '../../lib/tts/wav.mjs';

const AO = 'skills/plate-factory/scripts/audio-options.mjs';
let work, pack, project;

/** 0.5 s of a 440 Hz sine, 48 kHz mono s16le, as WAV. */
function tone() {
  const n = 24000, pcm = Buffer.alloc(n * 2);
  for (let i = 0; i < n; i++) pcm.writeInt16LE(Math.round(8000 * Math.sin((2 * Math.PI * 440 * i) / 48000)), i * 2);
  return pcmToWav(pcm, { sampleRate: 48000 });
}

before(() => {
  work = tmpDir('pm-audio-options-');
  pack = path.join(work, 'pack');
  cpSync(fx('brand-min'), pack, { recursive: true });
  mkdirSync(path.join(pack, 'music'));
  mkdirSync(path.join(pack, 'sfx'));
  writeFileSync(path.join(pack, 'music', 'tone-bed.wav'), tone());
  writeFileSync(path.join(pack, 'sfx', 'tone-hit.wav'), tone());
  writeFileSync(path.join(pack, 'stray.wav'), tone()); // not listed: must not be offered
  writeFileSync(path.join(pack, 'sfx', 'manifest.json'), JSON.stringify({ files: [{ title: 'Tone hit', file: 'tone-hit.wav', source: 'generated by this test', licence: 'CC0', durationMs: 500, peakOffsetMs: 10 }] }));
  const brand = JSON.parse(readFileSync(path.join(pack, 'brand.json'), 'utf8'));
  writeFileSync(path.join(pack, 'brand.json'), JSON.stringify({ ...brand, 'x-tracks': [{ title: 'Tone bed', file: 'music/tone-bed.wav', credit: 'Test tone (CC0)', levels: { musicLufs: -28, duckDb: 6 } }], 'x-sfx': 'sfx/manifest.json' }, null, 2));
  project = path.join(work, 'video');
  mkdirSync(path.join(project, 'audio'), { recursive: true });
  writeFileSync(path.join(project, 'plates.json'), JSON.stringify({ schemaVersion: 1, brand: '../pack', plates: [] }));
  writeFileSync(path.join(project, 'audio', 'leftover.wav'), tone()); // in the project, not offered
});

test('stage 8: audio-options lists the pack\'s x-tracks and SFX by name, with credit and levels', () => {
  const r = run(AO, [project, '--json']);
  assert.equal(r.code, 0, r.stderr);
  const j = JSON.parse(r.stdout);
  assert.equal(j.pack, 'Minimal test pack');
  assert.deepEqual(j.tracks.map((t) => [t.title, t.file, t.credit, t.levels]), [['Tone bed', path.join(pack, 'music', 'tone-bed.wav'), 'Test tone (CC0)', { musicLufs: -28, duckDb: 6 }]]);
  assert.deepEqual(j.sfx.map((s) => [s.title, s.file, s.licence, s.durationMs, s.peakOffsetMs]), [['Tone hit', path.join(pack, 'sfx', 'tone-hit.wav'), 'CC0', 500, 10]]);
  assert.ok(!r.stdout.includes('stray.wav') && !r.stdout.includes('leftover.wav'), 'only listed audio is offered; nothing is searched for');
  const text = run(AO, [path.join(pack, 'brand.json')]);
  assert.equal(text.code, 0, text.stderr);
  assert.match(text.stdout, /^music {2}Tone bed .*--music-lufs -28 --duck-db 6/m);
  assert.match(text.stdout, /^sfx {4}Tone hit .*licence: CC0/m);
});

test('stage 8: a pack with no tracks says so (ask for a folder, else narration only); a missing listed file fails in one line', () => {
  const r = run(AO, [path.join(ROOT, 'brand-packs', 'default')]);
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /no pack tracks or SFX — ask the user for a folder \(--folder\), else narration only/);
  const broken = path.join(work, 'broken');
  cpSync(pack, broken, { recursive: true });
  const b = JSON.parse(readFileSync(path.join(broken, 'brand.json'), 'utf8'));
  writeFileSync(path.join(broken, 'brand.json'), JSON.stringify({ ...b, 'x-tracks': [{ title: 'Gone', file: 'music/gone.mp3' }] }));
  const m = run(AO, [broken]);
  assert.equal(m.code, 1);
  assert.match(m.stderr, /pack lists audio that is missing: .*gone\.mp3/);
  assert.equal(m.stderr.trim().split('\n').length, 1, 'one-line error');
});

test('stage 8: --folder lists only the audio files directly in the folder the user named', () => {
  const dir = path.join(work, 'user-music');
  mkdirSync(path.join(dir, 'nested'), { recursive: true });
  writeFileSync(path.join(dir, 'b-track.wav'), tone());
  writeFileSync(path.join(dir, 'a-track.mp3'), Buffer.from('not checked'));
  writeFileSync(path.join(dir, 'notes.txt'), 'x');
  writeFileSync(path.join(dir, 'nested', 'deep.wav'), tone());
  const r = run(AO, ['--folder', dir, '--json']);
  assert.equal(r.code, 0, r.stderr);
  assert.deepEqual(JSON.parse(r.stdout).files.map((f) => f.title), ['a-track.mp3', 'b-track.wav']);
  const none = run(AO, ['--folder', path.join(dir, 'nested', '..', 'nested'), '--json']);
  assert.deepEqual(JSON.parse(none.stdout).files.map((f) => f.title), ['deep.wav']);
});

test('stage 8: stages.md tells the agent to offer pack tracks, then a named folder, then narration only', () => {
  const md = readFileSync(path.join(ROOT, 'skills', 'plate-factory', 'references', 'stages.md'), 'utf8');
  const s8 = md.slice(md.indexOf('## Stage 8'), md.indexOf('## Stage 9'));
  for (const want of ['audio-options.mjs" plates.json', '--folder <dir>', 'Else narration only', 'never search the disk']) assert.ok(s8.includes(want), `stage 8 says: ${want}`);
});
